// Builds route-geometry.js so the map line follows real roads without any live API calls.
// Run from the repo folder with Node 18 or newer:   node tools/build-route.mjs
// Uses the free OSRM demo server (OpenStreetMap data). Re-run whenever you change TRIP.route in data.js.

import fs from "node:fs";
import vm from "node:vm";

const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync("data.js", "utf8"), ctx);
const route = ctx.window.TRIP.route;

const CHUNK = 25;
const pts = [];
for (let i = 0; i < route.length - 1; i += CHUNK - 1) {
  const part = route.slice(i, i + CHUNK);
  const coords = part.map(([lat, lng]) => `${lng.toFixed(5)},${lat.toFixed(5)}`).join(";");
  const url = `https://router.project-osrm.org/route/v1/driving/${coords}?overview=simplified&geometries=geojson`;
  const res = await fetch(url);
  const data = await res.json();
  if (data.code !== "Ok") throw new Error(`Routing failed for points ${i}-${i + part.length - 1}: ${data.code}`);
  data.routes[0].geometry.coordinates.forEach(([lng, lat]) => pts.push([+lat.toFixed(4), +lng.toFixed(4)]));
  console.log(`Routed points ${i + 1}-${i + part.length} of ${route.length}`);
  await new Promise(r => setTimeout(r, 1100));
}

fs.writeFileSync("route-geometry.js",
  "// Generated by tools/build-route.mjs from OpenStreetMap data via OSRM.\n" +
  "window.ROUTE_GEOMETRY = " + JSON.stringify(pts) + ";\n");
console.log(`Wrote route-geometry.js with ${pts.length} points.`);
